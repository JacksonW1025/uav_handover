#!/usr/bin/env python3
"""P6 condition generation and the identification profiles (pure functions of the config; used by the runner, the batch
tool and the tests).

p5_gap conditions (B, C): names 'v<speed>-D<duration>-<A0|A45>' (one interruption) or '<pattern>-<A0|A45>' (explicit
window list from p5.c2_patterns). The spec is generated from the template in config p5.condition_rule and fitted into the
pre-registered safety budget: the P5 path check (runner Experiment.p5_path_check) at the spawn point plus
p5.planned_path_check.hover_offset_allowance_m <= 8 m; if it does not fit, the hold after the last resume (post_gap_s) is
shortened in 0.05 s steps down to 2.0 s, then the cruise before the first interruption (pre_gap_s) down to 0.75 s; if it
still does not fit the condition is cancelled (never flown). Speed and interruption lengths are never changed.

p6_ident conditions: families step / chase / brake / capture (config p6.ident). Profile time = reposition to the start
offset (centring the planned path on RAPTOR's hover capture), reference hold, family motion, end hold.
"""
import math,re
from types import SimpleNamespace

AXES={'A0':[1.0,0.0,0.0],'A45':[0.70710678,0.70710678,0.0]}
GAP_NAME=re.compile(r'^v(?P<v>\d+(?:\.\d+)?)-D(?P<D>\d+(?:\.\d+)?)-(?P<axis>A0|A45)$')

def fmt(x):
    """Canonical number text in condition names (at most 4 decimals, no trailing zeros; 1.5 -> '1.5', 2.0 -> '2.0')."""
    s=('%.4f'%float(x)).rstrip('0');return s+'0' if s.endswith('.') else s

def gap_name(v,D,axis):return f'v{fmt(v)}-D{fmt(D)}-{axis}'

# ---- p5_gap conditions ----------------------------------------------------------------------------------------------
def budget(cfg,p5,spec):
    """P5 runner path check at the spawn point for a candidate spec (same code as the run-time check)."""
    from run_experiment import Experiment,p5_profile
    e=SimpleNamespace(pcfg=p5_profile(p5,spec),cfg={'p1_speed_m_s':float(spec['speed_m_s']),'safety_radius_m':cfg['safety_radius_m'],'p5':p5})
    e.p5_gap_windows=lambda:Experiment.p5_gap_windows(e)
    c=Experiment.p5_path_check(e,[0.,0.,-float(cfg['altitude_m'])])
    allow=float(p5['planned_path_check']['hover_offset_allowance_m'])
    return {'path_m':round(c['path_m'],6),'radius_at_spawn_m':round(c['radius_with_allowance_m'],6),'interruption_drift_m':round(c['interruption_drift_m'],6),
            'hover_offset_allowance_m':allow,'radius_m':round(c['radius_with_allowance_m']+allow,6),'limit_m':c['limit_m'],
            'inside':c['radius_with_allowance_m']+allow<=c['limit_m']+1e-9}

def fit(cfg,p5,base):
    """Pre-registered shrink order: post_gap_s 3.0 -> 2.0 (0.05 s steps), then pre_gap_s 1.0 -> 0.75; else cancelled."""
    r=p5['condition_rule'];prof=p5['profile'];step=float(r['shrink_step_s'])
    post0,pre0=float(prof['post_gap_s']),float(prof['pre_gap_s']);post_min,pre_min=float(r['post_gap_min_s']),float(r['pre_gap_min_s'])
    tries=[(pre0,round(post0-k*step,6)) for k in range(int(round((post0-post_min)/step))+1)]
    tries+=[(round(pre0-k*step,6),post_min) for k in range(1,int(round((pre0-pre_min)/step))+1)]
    for pre,post in tries:
        spec={**base,'pre_gap_s':pre,'post_gap_s':post};b=budget(cfg,p5,spec)
        if b['inside']:
            spec['safety_budget_m']=b;spec['shrunk']={'post_gap_s':post!=post0,'pre_gap_s':pre!=pre0};return spec
    last={**base,'pre_gap_s':pre_min,'post_gap_s':post_min}
    return {**base,'cancelled':True,'cancel_reason':'does not fit the safety budget with post_gap_s 2.0 s and pre_gap_s 0.75 s','safety_budget_m':budget(cfg,p5,last)}

def gap_spec(cfg,name):
    """Generated p5_gap condition spec for a P6 name, or None when the name is not a P6 gap condition."""
    p5=cfg['p5'];r=p5.get('condition_rule')
    if not r:return None
    m=GAP_NAME.match(name)
    if m:
        v,D,axis=float(m['v']),float(m['D']),m['axis']
        if fmt(v)!=m['v'] or fmt(D)!=m['D']:return None
        if v not in [float(x) for x in r['speeds_m_s']] or not float(r['duration_min_s'])<=D<=float(r['duration_max_s']):return None
        base={'speed_m_s':v,'motion_axis_ned':AXES[axis],'gaps':{'count':1,'duration_s':D,'recover_s':0.0},'flight_failures_are_results':True,
              'description':f'P6 single interruption D = {fmt(D)} s at {fmt(v)} m/s, {axis} (generated by p5.condition_rule)'}
        return fit(cfg,p5,base)
    pat,_,axis=name.rpartition('-')
    if pat in p5.get('c2_patterns',{}) and axis in AXES:
        c=p5['c2_patterns'][pat];windows=[[float(a),float(b)] for a,b in c['windows_s']]
        base={'speed_m_s':float(c['speed_m_s']),'motion_axis_ned':AXES[axis],'gaps':{'windows_s':windows},'flight_failures_are_results':True,
              'description':f"P6 C2 {pat}: {c['description']}, {axis}"}
        return fit(cfg,p5,base)
    return None

# ---- p6_ident ---------------------------------------------------------------------------------------------------------
def ident_cfg(cfg,name):
    """Merged profile configuration of a p6_ident condition (planned worst-case path centred on the hover capture)."""
    p6=cfg['p6']['ident'];spec=p6['conditions'][name];f=spec['family'];fam=p6['families'][f]
    p={**p6['profile'],**{k:v for k,v in fam.items() if k!='description'},**{k:v for k,v in spec.items() if k not in ['description','safety_budget_m']}}
    p['motion_axis_ned']=AXES[spec['axis']]
    p['path_length_m']=ident_length(p);p['start_offset_m']=-round(p['path_length_m']/2,6)
    return p

def ident_length(p):
    """Planned along-axis extent of the target from the start offset (chase: switch at the latest, max_chase_s)."""
    f=p['family']
    if f=='step':return float(p['step_m'])
    if f=='chase':
        V=float(p['speed_m_s']);return float(p['x0_m'])+V*float(p['max_chase_s'])+V*V/(2*float(p['stop_decel_m_s2']))
    if f=='brake':
        V=float(p['speed_m_s']);return V*V/(2*float(p['accel_m_s2']))+V*float(p['cruise_s'])+V*V/(2*float(p['brake_m_s2']))
    if f=='capture':
        v=float(p['speed_m_s']);return .5*v*float(p['accel_s'])+v*(float(p['pre_gap_s'])+float(p['gap_s']))+v*v/(2*float(p['stop_decel_m_s2']))
    raise ValueError(f)

def ident_motion(p,tau,switch=None):
    """Family motion at time tau after the family start: (s from the start offset, v, a) along the axis.
    chase: switch = time of the deceleration start (None: not yet decided, the target keeps cruising)."""
    f=p['family']
    if tau<0:return 0.,0.,0.
    if f=='step':return float(p['step_m']),0.,0.
    if f=='chase':
        x0,V,b=float(p['x0_m']),float(p['speed_m_s']),float(p['stop_decel_m_s2'])
        if switch is None or tau<switch:return x0+V*tau,V,0.
        r=min(tau-switch,V/b);return x0+V*switch+V*r-.5*b*r*r,V-b*r,(-b if tau-switch<V/b else 0.)
    if f=='brake':
        V,a,c,b=float(p['speed_m_s']),float(p['accel_m_s2']),float(p['cruise_s']),float(p['brake_m_s2'])
        ta=V/a
        if tau<ta:return .5*a*tau*tau,a*tau,a
        if tau<ta+c:return .5*V*ta+V*(tau-ta),V,0.
        r=min(tau-ta-c,V/b);return .5*V*ta+V*c+V*r-.5*b*r*r,V-b*r,(-b if tau-ta-c<V/b else 0.)
    if f=='capture':
        v,acc,cr,b=float(p['speed_m_s']),float(p['accel_s']),float(p['pre_gap_s'])+float(p['gap_s']),float(p['stop_decel_m_s2'])
        if tau<acc:return .5*v*tau*tau/acc,v*tau/acc,v/acc
        if tau<acc+cr:return .5*v*acc+v*(tau-acc),v,0.
        r=min(tau-acc-cr,v/b);return .5*v*acc+v*cr+v*r-.5*b*r*r,v-b*r,(-b if tau-acc-cr<v/b else 0.)
    raise ValueError(f)

def ident_motion_duration(p,switch=None):
    """Family motion time until the target is at rest (chase: with the switch, or max_chase_s if not yet decided)."""
    f=p['family']
    if f=='step':return 0.
    if f=='chase':return (float(p['max_chase_s']) if switch is None else switch)+float(p['speed_m_s'])/float(p['stop_decel_m_s2'])
    if f=='brake':V=float(p['speed_m_s']);return V/float(p['accel_m_s2'])+float(p['cruise_s'])+V/float(p['brake_m_s2'])
    if f=='capture':v=float(p['speed_m_s']);return float(p['accel_s'])+float(p['pre_gap_s'])+float(p['gap_s'])+v/float(p['stop_decel_m_s2'])
    raise ValueError(f)

def ident_gap(p):
    """capture family: the stream pause in family time [start, end) (none for the other families)."""
    if p['family']!='capture':return None
    a=float(p['accel_s'])+float(p['pre_gap_s']);return (a,a+float(p['gap_s']))

def ident_budget(cfg,name):
    """Pre-registered path check at the spawn point: max(|start|,|end|) of the centred worst-case path + braking allowance +
    hover-offset allowance <= safety_radius_m - radius_margin_m (P5 rule; no interruption drift: only the capture family
    pauses, with a zero-velocity capture behind the moving trajectory point)."""
    p=ident_cfg(cfg,name);c=cfg['p6']['ident']['planned_path_check'];L=p['path_length_m']
    half=max(abs(p['start_offset_m']),abs(p['start_offset_m']+L))
    radius=half+float(c['braking_allowance_m']);limit=cfg['safety_radius_m']-float(c['radius_margin_m'])
    allow=float(c['hover_offset_allowance_m'])
    return {'path_m':round(L,6),'radius_at_spawn_m':round(radius,6),'hover_offset_allowance_m':allow,'radius_m':round(radius+allow,6),'limit_m':limit,'inside':radius+allow<=limit+1e-9}

